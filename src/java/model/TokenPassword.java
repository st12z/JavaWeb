package model;

/**
 *
 * @author T
 */
public class TokenPassword {
    private String email;
    private String token;

    public TokenPassword(String email, String token) {
        this.email = email;
        this.token = token;
    }

    public String getEmail() {
        return email;
    }

    public String getToken() {
        return token;
    }
    
}
